// Writes README.md. Images come from the `output` branch that the workflow refreshes every day.
import { writeFileSync } from "node:fs";
import { links, projects } from "./data/profile.mjs";

const login = process.env.PROFILE_LOGIN ?? "AmirSarfaraz";
const base = process.env.ASSET_BASE ?? `https://raw.githubusercontent.com/${login}/${login}/output`;
const img = (file, width, alt) => `<img src="${base}/${file}" width="${width}" alt="${alt}" />`;

const buttons = links.map((l) => `<a href="${l.href}">${img(`btn-${l.key}.svg`, 206, l.label)}</a>`).join("\n");
const cardRows = [];
for (let i = 0; i < projects.length; i += 2) {
  cardRows.push(projects.slice(i, i + 2).map((p) => `<a href="${p.href}">${img(`projects/${p.slug}.svg`, 410, `${p.name} — ${p.text.join(" ")}`)}</a>`).join("\n"));
}

const readme = `<div align="center">

${img("header.svg", 860, "Amir Sarfaraz — Back-End .NET Developer")}

${buttons}

${img("whoami.svg", 860, "whoami — ASCII portrait and a neofetch-style card: Amirhossein Sarfaraz, Back-End .NET Developer in Tehran")}

${img("contributions.svg", 860, "Contribution graph of the last year, played as Galaga")}

${img("stack.svg", 860, "Tech stack: C#, .NET, ASP.NET Core, SQL Server, PostgreSQL, React, TypeScript, Docker, PyTorch and more")}

${cardRows.join("\n\n")}

<sub>Every panel is an SVG generated by <a href=".github/workflows/profile.yml">a GitHub Action</a> that runs daily · Galaga by <a href="https://github.com/abozanona/pacman-contribution-graph">pacman-contribution-graph</a></sub>

</div>
`;
writeFileSync(process.env.README_OUT ?? "README.md", readme);
console.log("README written", readme.length, "chars");
